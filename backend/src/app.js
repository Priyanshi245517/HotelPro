const express = require("express");
const cors = require("cors");
const helmet = require("helmet");
const rateLimit = require("express-rate-limit");
const { protect, allow } = require("./middleware/auth");
const auth = require("./controllers/auth");
const rooms = require("./controllers/rooms");
const bookings = require("./controllers/bookings");
const dashboard = require("./controllers/dashboard");
const { notFound, errors } = require("./middleware/errors");

const app = express();
const origins = (process.env.CLIENT_ORIGIN || "http://localhost:5173").split(",").map(s => s.trim());
app.use(helmet());
app.use(cors({ origin: origins, credentials: false }));
app.use(express.json({ limit: "20kb" }));
app.use("/api/auth", rateLimit({ windowMs: 15 * 60 * 1000, limit: 100 }));
app.get("/api/health", (req, res) => res.json({ status: "ok", service: "HotelPro API" }));
app.post("/api/auth/register", auth.register);
app.post("/api/auth/login", auth.login);
app.get("/api/auth/me", protect, auth.me);
app.get("/api/rooms", rooms.list);
app.post("/api/rooms", protect, allow("staff", "admin"), rooms.create);
app.patch("/api/rooms/:id", protect, allow("staff", "admin"), rooms.update);
app.delete("/api/rooms/:id", protect, allow("admin"), rooms.deactivate);
app.post("/api/bookings", protect, bookings.create);
app.get("/api/bookings", protect, bookings.list);
app.patch("/api/bookings/:id/cancel", protect, bookings.cancel);
app.get("/api/dashboard", protect, allow("staff", "admin"), dashboard.summary);
app.use(notFound);
app.use(errors);
module.exports = app;
